create table if not exists public.policy (
  id integer primary key default 1,
  daily_cap numeric not null default 15,
  per_tx_cap numeric not null default 10,
  allowed_payees jsonb not null default '[]'::jsonb
);

create table if not exists public.transactions (
  id bigint generated by default as identity primary key,
  ts timestamptz not null default now(),
  resource text not null,
  amount numeric not null,
  payee text not null,
  reason text,
  status text not null check (status in ('auto_approved', 'blocked', 'pending_owner', 'owner_approved')),
  tx_hash text,
  blocked_reason text
);

create table if not exists public.staff_users (
  id bigint generated by default as identity primary key,
  username text not null unique,
  display_name text not null,
  passcode text not null,
  role text not null default 'staff' check (role in ('staff', 'owner')),
  active boolean not null default true,
  shift text not null default 'Flexible Shift',
  created_at timestamptz not null default now()
);

